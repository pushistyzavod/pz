const rows = [];
const seen = new Set();
function add(cluster, url, q, type) {
  q = q.trim().replace(/\s+/g, ' ').toLowerCase();
  if (q.length < 4 || seen.has(q)) return;
  seen.add(q);
  rows.push({ cluster, url, q, type });
}

